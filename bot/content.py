def term_by_verb(verb: str) -> dict | None:
    for term in TERMS:
        if term["verb"] == verb:
            return term
    return None


def terms_in_category(category: str) -> list[dict]:
    return [t for t in TERMS if t["category"] == category]


def contrast_groups() -> dict[str, list[dict]]:
    """Возвращает контрастные пары: {group: [term, term]}."""
    groups: dict[str, list[dict]] = {}
    for t in TERMS:
        if t["contrast_group"]:
            groups.setdefault(t["contrast_group"], []).append(t)
    return groups